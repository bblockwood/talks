// Regenerates fixtures/crypto-vectors.json and fixtures/encrypted-sample.bin (SPEC §11, fixture 12).
//
// This is the *reference* implementation: it uses Node's OpenSSL bindings (pbkdf2Sync, hkdfSync,
// createCipheriv), not WebCrypto, so the vectors are an independent check on src/core/crypto.ts.
// Run it only when the scheme in SPEC §3–4 changes:  node tools/make-test-vectors.ts
import { createCipheriv, createHash, hkdfSync, pbkdf2Sync } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { packPayload } from "../src/core/payload.ts";

const root = path.resolve(import.meta.dirname, "..");
const hex = (b: Uint8Array | ArrayBuffer): string => Buffer.from(b as Uint8Array).toString("hex");

function derive(code: string) {
  const base = pbkdf2Sync(code, "lectern-web-v1", 600_000, 32, "sha256");
  const expand = (info: string, bytes: number): string => hex(hkdfSync("sha256", base, Buffer.alloc(0), info, bytes));
  return {
    code,
    deckId: expand("deck-id", 16),
    deckKey: expand("deck-key", 32),
    roomId: expand("room-id", 16),
    channelKey: expand("channel-key", 32),
  };
}

function encrypt(keyHex: string, iv: Buffer, plaintext: Uint8Array): Buffer {
  const cipher = createCipheriv("aes-256-gcm", Buffer.from(keyHex, "hex"), iv);
  const body = Buffer.concat([cipher.update(plaintext), cipher.final(), cipher.getAuthTag()]);
  return Buffer.concat([Buffer.from("LCTW"), Buffer.from([1]), iv, body]);
}

// Codes here are test-only and public. They are already normalised.
const derivations = ["example-word", "otter-maple-quiz-lunar", "abc", "lectern-test-vector"].map(derive);

const iv = Buffer.from("000102030405060708090a0b", "hex");
const plaintext = Buffer.from("Lectern test vector payload ✓", "utf8");
const messageKey = derivations[0]!.deckKey;
const file = {
  code: derivations[0]!.code,
  iv: hex(iv),
  plaintext: hex(plaintext),
  bin: hex(encrypt(messageKey, iv, plaintext)),
};

// Fixture 12: a whole deck, encrypted with a fixed code and a fixed iv.
const sampleCode = "lectern-test-vector";
const sampleKeys = derivations.find((d) => d.code === sampleCode)!;
const published = "2026-01-01T00:00:00.000Z";
const payload = packPayload({
  pdf: readFileSync(path.join(root, "fixtures/basic-169.pdf")),
  meta: { v: 1, title: "Basic 16:9", published, source: "basic-169.pdf", pageCount: 20, settings: {}, noteOverrides: [] },
  notes: null,
  pdfpc: null,
});
const sampleBin = encrypt(sampleKeys.deckKey, iv, payload);
writeFileSync(path.join(root, "fixtures/encrypted-sample.bin"), sampleBin);

const vectors = {
  about: "Generated by tools/make-test-vectors.ts with Node's OpenSSL bindings. Test-only codes.",
  pbkdf2: { salt: "lectern-web-v1", iterations: 600_000, hash: "SHA-256", bits: 256 },
  hkdf: { hash: "SHA-256", salt: "", info: ["deck-id", "deck-key", "room-id", "channel-key"] },
  derivations,
  file,
  sample: {
    file: "encrypted-sample.bin",
    code: sampleCode,
    iv: hex(iv),
    published,
    sha256: createHash("sha256").update(sampleBin).digest("hex"),
    pdfSha256: createHash("sha256").update(readFileSync(path.join(root, "fixtures/basic-169.pdf"))).digest("hex"),
  },
};
writeFileSync(path.join(root, "fixtures/crypto-vectors.json"), JSON.stringify(vectors, null, 2) + "\n");
console.log("wrote fixtures/crypto-vectors.json and fixtures/encrypted-sample.bin");
